"""tools/gen_shots.py — 2.3 routine shots from templates, special shots in batches.

  python tools/gen_shots.py --project projects/<slug>                     write the auto shots
  python tools/gen_shots.py --project projects/<slug> --batches            + story/batches.json and story/slices/<bid>.json
  python tools/gen_shots.py --project projects/<slug> --batches --batch-size 18

Reads story/tpl_spec.py (written per video by the kit-builder agent):
    from gen_shots import c, PI, H
    MANUAL = {'s002': 'glass shards macro', ...}          # special shots and why (hand-written in batches)
    SPEC = {'s001': dict(kind='establish', fx=['smoke'], cast=[c('KAI', 'A', expr='shocked')]), ...}
Every shot in SPEC (and not in MANUAL) gets a "tpl" in story/shots.json and one shotT() line in
scenes/shots/auto_<place>.js (rewritten every run: never edit those files; fix scenes/_places.js or the SPEC).
A shot in neither list is manual ("unclassified"). Ends with one line: RESULT ok|fail ...
"""
import argparse, importlib.util, json, math, os, sys
from collections import OrderedDict

PI, H = math.pi, math.pi / 2
KIND_CAM = {'establish': None, 'wide': None, 'dialogue': None, 'reaction': None, 'xcu': 'xcu', 'insert': 'insert', 'walk': 'track', 'stage': None}
KINDS = set(KIND_CAM)


def c(id, at='A', **kw):
    """one cast entry: c('KAI', 'B', face='MIA', expr=[[0, 'sad'], [1.2, 'smile']], pose='kneel', glow=0.8)"""
    d = {'id': id, 'at': at}; d.update(kw); return d


def tpl_for(s, spec):
    sp = dict(spec); t = OrderedDict(); t['kind'] = sp.pop('kind'); t['place'] = 'stage' if t['kind'] == 'stage' else s.get('place') or s.get('set')
    cam0 = s.get('camera')
    cam = sp.pop('cam', None) or KIND_CAM[t['kind']] or cam0
    if t['kind'] == 'establish' and cam not in ('establish', 'craneDown', 'craneUp'): cam = cam0 if cam0 in ('establish', 'craneDown') else 'establish'
    if t['kind'] == 'reaction' and cam not in ('closeup', 'pushIn'): cam = 'closeup'
    if t['kind'] == 'dialogue' and cam not in ('medium', 'twoShot', 'ots', 'orbit'): cam = 'medium'
    t['cam'] = cam; t.update(sp); return t


def emit_js(auto, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    for f in os.listdir(out_dir):
        if f.startswith('auto_') and f.endswith('.js'): os.remove(os.path.join(out_dir, f))
    by = OrderedDict()
    for s in auto: by.setdefault(s['tpl']['place'], []).append(s)
    for place, L in by.items():
        lines = [f'// auto_{place}.js — GENERATED by tools/gen_shots.py from story/tpl_spec.py ({len(L)} shots). Do not edit: fix scenes/_places.js or the SPEC.',
                 "import { shotT } from '../_places.js';", '']
        for s in L:
            lines.append(f"//@ {s['id']} | {s.get('camera', '')} | {str(s.get('scene', ''))[:90]}")
            lines.append(f"shotT('{s['id']}', {json.dumps(s['tpl'], ensure_ascii=False, separators=(',', ':'))});")
        with open(os.path.join(out_dir, f'auto_{place}.js'), 'w', encoding='utf-8') as fh: fh.write('\n'.join(lines) + '\n')
    return by


def batches(shots, story, size):
    """manual shots only, in story order, ~size per batch, cuts nudged (±2) onto a place change; each slice lists the auto
    shots around it (neighbours_auto) so a batch can match their spots, faces and screen direction."""
    order = [s['id'] for s in shots]; idx = {k: i for i, k in enumerate(order)}; auto = {s['id'] for s in shots if s.get('auto')}
    place = lambda s: s.get('place') or s.get('set')
    man = [s for s in shots if not s.get('auto')]
    if not man: return []
    k = max(1, round(len(man) / size)); cuts = [0]
    for i in range(1, k):
        c0 = round(i * len(man) / k); best = c0
        for d in (0, 1, -1, 2, -2):
            j = c0 + d
            if 0 < j < len(man) and place(man[j]) != place(man[j - 1]): best = j; break
        cuts.append(best)
    cuts.append(len(man)); out = [man[a:b] for a, b in zip(cuts, cuts[1:]) if b > a]
    sl = os.path.join(story, 'slices'); os.makedirs(sl, exist_ok=True)
    for f in os.listdir(sl):
        if f.endswith('.json'): os.remove(os.path.join(sl, f))
    B = []
    for i, L in enumerate(out, 1):
        bid = f'm{i:02d}'; ids = [s['id'] for s in L]; nb = set()
        for sid in ids:
            for d in (-1, 1):
                j = idx[sid] + d
                while 0 <= j < len(order) and order[j] not in auto and order[j] in ids: j += d
                if 0 <= j < len(order) and order[j] in auto: nb.add(order[j])
        places = list(OrderedDict.fromkeys(place(s) for s in L))
        B.append({'id': bid, 'shots': ids, 'places': places, 'file': f'scenes/shots/{bid}_{places[0]}.js', 'slice': f'story/slices/{bid}.json', 'neighbours': sorted(nb)})
        with open(os.path.join(sl, f'{bid}.json'), 'w', encoding='utf-8') as fh:
            json.dump({'batch': bid, 'places': places, 'neighbours_auto': [s for s in shots if s['id'] in nb], 'shots': L}, fh, ensure_ascii=False, indent=1)
    with open(os.path.join(story, 'batches.json'), 'w', encoding='utf-8') as fh:
        json.dump({'note': 'manual shots only (auto shots come from scenes/_places.js via tools/gen_shots.py)', 'batches': B}, fh, ensure_ascii=False, indent=1)
    return B


def load_spec(path):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # so the spec can `from gen_shots import c, PI, H`
    sys.modules.setdefault('gen_shots', sys.modules[__name__])
    sp = importlib.util.spec_from_file_location('tpl_spec', path); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m)
    return getattr(m, 'MANUAL', {}), getattr(m, 'SPEC', {})


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--project', required=True); ap.add_argument('--batches', action='store_true')
    ap.add_argument('--batch-size', type=int, default=18); ap.add_argument('--spec', default=None)
    a = ap.parse_args()
    P = os.path.abspath(a.project); story = os.path.join(P, 'story'); shots_p = os.path.join(story, 'shots.json')
    spec_p = a.spec or os.path.join(story, 'tpl_spec.py')
    if not os.path.exists(spec_p): print(f'RESULT fail no {os.path.relpath(spec_p, P)} (MANUAL + SPEC, see references/templates.md)'); sys.exit(1)
    if not os.path.exists(os.path.join(P, 'scenes', '_places.js')): print('RESULT fail no scenes/_places.js (makeTemplates config, see references/templates.md)'); sys.exit(1)
    MANUAL, SPEC = load_spec(spec_p)
    raw = open(shots_p, encoding='utf-8').read().lstrip('﻿'); d = json.loads(raw); shots = d['shots']
    ids = {s['id'] for s in shots}
    bad = [f'{k}: kind {v.get("kind")!r}' for k, v in SPEC.items() if v.get('kind') not in KINDS]
    ghost = sorted((set(SPEC) | set(MANUAL)) - ids)
    if bad: print('RESULT fail SPEC has unknown kinds: ' + '; '.join(bad[:8])); sys.exit(1)
    if ghost: print('WARNING ids in tpl_spec.py that are not in shots.json: ' + ' '.join(ghost[:20]))
    unknown = [s['id'] for s in shots if s['id'] not in SPEC and s['id'] not in MANUAL]
    if unknown: print('UNCLASSIFIED (manual by default): ' + ' '.join(unknown))
    for s in shots:
        s.pop('tpl', None); s.pop('manual', None)
        if s['id'] in SPEC and s['id'] not in MANUAL: s['auto'] = True; s['tpl'] = tpl_for(s, SPEC[s['id']])
        else: s['auto'] = False; s['manual'] = MANUAL.get(s['id'], 'unclassified')
    auto = [s for s in shots if s['auto']]
    by = emit_js(auto, os.path.join(P, 'scenes', 'shots'))
    with open(shots_p, 'w', encoding='utf-8') as fh: json.dump(d, fh, ensure_ascii=False, indent=1)
    share = 100 * len(auto) / max(1, len(shots))
    for p, L in by.items(): print(f'  auto_{p}.js: {",".join(s["id"] for s in L)}')
    B = batches(shots, story, a.batch_size) if a.batches else []
    for b in B: print(f"  {b['id']}: {len(b['shots'])} shots {'/'.join(b['places'])}  {b['shots'][0]}..{b['shots'][-1]}")
    warn = f'; auto share {share:.0f}% is over 60%: keep the hook, the climax, reveals and props in action hand-made' if share > 60 else ''
    print(f'RESULT ok auto {len(auto)} / manual {len(shots) - len(auto)} / total {len(shots)} ({share:.0f}% auto)'
          + (f', {len(B)} batch(es) -> story/batches.json' if a.batches else '') + warn)


if __name__ == '__main__':
    main()
