"""tools/example_index.py - 2.2 write examples/INDEX.md: every engine call the example scenes use -> where (file:line).

  python tools/example_index.py            (verify_kit.py runs it too, so the index follows the examples)

Building a shot, look the call up in examples/INDEX.md and open only those lines (Read with offset/limit), instead of reading
the example folders. The first table says what each example folder shows.
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX = os.path.join(ROOT, "examples")
CALL = re.compile(r"\b((?:T\.(?:W|usa|FX3|cam|D)\.|T\.|D\.|FX3\.|W\.)[A-Za-z_]\w*)\s*\(")
METHOD = re.compile(r"\.(walkTo|sitOn|climbOn|runStop|trip|vault|hug|highFive|carry|door|catchFall|pullRun|armAround|lookAtSpeaker|gaze|react|"
                    r"posesAt3|idle3|speak3|face|pose|place|crashZoom|punch|smash|ramp|rackFocus|follow|orbit|dolly|establish|craneDown|wordTime|"
                    r"frameHead|placeAt|watch|heroLights|powerGlow|backdrop|counters|newsWall|feedDraw|scoreboard3d|billboard|formation|stadium|"
                    r"slice|sparks|debris|smoke|splash|mirror|fire|blade|torch|glowLight)\s*\(")


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    where, about = {}, []
    for d in sorted(glob.glob(os.path.join(EX, "*", "scenes"))):
        name = os.path.basename(os.path.dirname(d))
        files = sorted(glob.glob(os.path.join(d, "**", "*.js"), recursive=True))
        first = ""
        for f in files:
            for line in open(f, encoding="utf-8", errors="ignore"):
                if line.startswith("//"):
                    first = line.lstrip("/ ").strip()
                    break
            if first:
                break
        about.append((name, len(files), first[:150]))
        for f in files:
            rel = os.path.relpath(f, ROOT).replace("\\", "/")
            for i, line in enumerate(open(f, encoding="utf-8", errors="ignore"), 1):
                calls = list(CALL.finditer(line))
                named = {c.group(1).split(".")[-1] for c in calls}
                for m in calls + [x for x in METHOD.finditer(line) if x.group(1) not in named]:
                    key = m.group(1) if m.re is CALL else "." + m.group(1)
                    lst = where.setdefault(key, [])
                    if len(lst) < 3 and not any(x.startswith(rel + ":") for x in lst):
                        lst.append(f"{rel}:{i}")
    L = ["# Example index (generated by tools/example_index.py; do not edit)", "",
         "Look up the call you need, then read only those lines (Read with offset/limit). Don't read whole example folders.", "",
         "## What each example shows", "", "| Folder | Files | First comment |", "|---|---|---|"]
    L += [f"| {n} | {k} | {a.replace('|', '/')} |" for n, k, a in about]
    L += ["", "## Calls -> where they are used (up to 3 places)", ""]
    for key in sorted(where, key=lambda k: (k.startswith("."), k.lower())):
        L.append(f"- `{key}` {', '.join(where[key])}")
    out = os.path.join(EX, "INDEX.md")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"examples/INDEX.md: {len(about)} example folders, {len(where)} calls")


if __name__ == "__main__":
    main()
